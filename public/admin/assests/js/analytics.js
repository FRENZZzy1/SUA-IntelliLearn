/**
 * analytics.js - System Analytics (teacher evaluation)
 *
 * - Teacher detail drawer (per-question scores, classes, written comments)
 * - "Generate AI summary" buttons (school-wide and per teacher)
 *
 * SECURITY: all data (including student comments and Gemini output) is put on
 * the page with textContent / createTextNode, never innerHTML.
 *
 * The AI summary lives only in the DOM. It is not saved anywhere, and it is
 * discarded when the drawer is closed or the page is left.
 */
(function () {
    'use strict';

    var dataEl = document.getElementById('evalData');
    if (!dataEl) return;

    var data = JSON.parse(dataEl.textContent);
    var teachers = {};
    (data.teachers || []).forEach(function (t) { teachers[t.teacher_id] = t; });

    // ---------- tiny DOM helpers ----------
    function el(tag, cls, text) {
        var node = document.createElement(tag);
        if (cls) node.className = cls;
        if (text !== undefined && text !== null) node.textContent = text;
        return node;
    }
    function icon(cls) {
        var i = document.createElement('i');
        i.className = 'fas ' + cls;
        return i;
    }
    function fmt(v) {
        return (v === null || v === undefined) ? '\u2014' : Number(v).toFixed(2);
    }
    function pct(v) {
        return v === null || v === undefined ? 0 : Math.round(Math.max(0, Math.min(5, v)) / 5 * 100);
    }
    function setButton(btn, iconCls, label) {
        btn.replaceChildren(icon(iconCls), document.createTextNode(' ' + label));
    }

    function barRow(label, value, widthPct, valueText, fillClass) {
        var row = el('div', 'an-bar-row');
        row.appendChild(el('div', 'an-bar-label', label));
        var track = el('div', 'an-bar-track');
        var fill = el('div', 'an-bar-fill' + (fillClass ? ' ' + fillClass : ''));
        fill.style.width = widthPct + '%';
        track.appendChild(fill);
        row.appendChild(track);
        row.appendChild(el('div', 'an-bar-value', valueText));
        return row;
    }

    function section(title, iconCls) {
        var wrap = el('section', 'an-drawer-section');
        var h = el('h3');
        if (iconCls) h.appendChild(icon(iconCls));
        h.appendChild(document.createTextNode(' ' + title));
        wrap.appendChild(h);
        return wrap;
    }

    // ---------- AI summary ----------
    function listBlock(title, items) {
        if (!items || !items.length) return null;
        var block = el('div', 'an-ai-block');
        block.appendChild(el('h4', null, title));
        var ul = el('ul');
        items.forEach(function (t) { ul.appendChild(el('li', null, t)); });
        block.appendChild(ul);
        return block;
    }

    function summaryToText(json) {
        var s = json.summary;
        var lines = [json.scope === 'school' ? 'AI SUMMARY (school-wide)' : 'AI SUMMARY (teacher)', '', s.overview, ''];
        [['Strengths', s.strengths], ['Areas for improvement', s.areas_for_improvement],
         ['Recurring comment themes', s.comment_themes], ['Suggested next steps', s.recommended_actions]]
            .forEach(function (pair) {
                if (pair[1] && pair[1].length) {
                    lines.push(pair[0]);
                    pair[1].forEach(function (i) { lines.push('- ' + i); });
                    lines.push('');
                }
            });
        lines.push('Generated by Gemini (' + json.model + ') on ' + new Date(json.generated_at).toLocaleString() + '. Not stored.');
        return lines.join('\n');
    }

    function renderSummary(out, json) {
        var s = json.summary;
        var card = el('div', 'an-ai-card');
        card.appendChild(el('p', 'an-ai-overview', s.overview));

        [listBlock('Strengths', s.strengths),
         listBlock('Areas for improvement', s.areas_for_improvement),
         listBlock('Recurring comment themes', s.comment_themes),
         listBlock('Suggested next steps', s.recommended_actions)]
            .forEach(function (b) { if (b) card.appendChild(b); });

        var foot = el('div', 'an-ai-foot');
        foot.appendChild(el('span', null,
            'Generated by Gemini just now \u00b7 not saved \u00b7 AI can make mistakes, so check it against the numbers above.'));
        var copy = el('button', 'btn btn-outline btn-sm');
        copy.type = 'button';
        setButton(copy, 'fa-copy', 'Copy text');
        copy.addEventListener('click', function () {
            var text = summaryToText(json);
            var done = function () {
                setButton(copy, 'fa-check', 'Copied');
                setTimeout(function () { setButton(copy, 'fa-copy', 'Copy text'); }, 1800);
            };
            if (navigator.clipboard && navigator.clipboard.writeText) {
                navigator.clipboard.writeText(text).then(done, function () { window.prompt('Copy the summary:', text); });
            } else {
                window.prompt('Copy the summary:', text);
            }
        });
        foot.appendChild(copy);
        card.appendChild(foot);

        out.replaceChildren(card);
    }

    function showAiError(out, message) {
        var box = el('div', 'an-ai-error');
        box.appendChild(icon('fa-triangle-exclamation'));
        box.appendChild(document.createTextNode(' ' + message));
        out.replaceChildren(box);
    }

    function requestSummary(teacherId, btn, out) {
        setButton(btn, 'fa-spinner fa-spin', 'Generating\u2026 this can take up to 30 seconds');
        btn.disabled = true;
        out.replaceChildren();

        fetch('assests/api/evaluation_ai_summary.php', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
            body: JSON.stringify({ round_id: data.roundId, teacher_id: teacherId || 0, csrf: data.csrf })
        })
        .then(function (res) {
            return res.json().catch(function () { return null; }).then(function (json) {
                if (!res.ok || !json || !json.success) {
                    var msg = json && (json.error || (json.errors && json.errors[0]));
                    throw new Error(msg || 'Something went wrong. Please try again.');
                }
                return json;
            });
        })
        .then(function (json) {
            renderSummary(out, json);
            setButton(btn, 'fa-rotate', 'Regenerate summary');
        })
        .catch(function (err) {
            showAiError(out, err.message);
            setButton(btn, 'fa-wand-magic-sparkles', 'Try again');
        })
        .then(function () { btn.disabled = false; });
    }

    // School-wide button (on the page itself)
    var schoolBtn = document.getElementById('schoolAiBtn');
    var schoolOut = document.getElementById('schoolAiResult');
    if (schoolBtn && schoolOut) {
        schoolBtn.addEventListener('click', function () { requestSummary(0, schoolBtn, schoolOut); });
    }

    // ---------- Teacher drawer ----------
    var drawer = document.getElementById('anDrawer');
    var overlay = document.getElementById('anOverlay');
    var titleEl = document.getElementById('anDrawerTitle');
    var metaEl = document.getElementById('anDrawerMeta');
    var bodyEl = document.getElementById('anDrawerBody');
    var closeBtn = document.getElementById('anClose');
    var lastFocus = null;

    function commentList(title, items, emptyText) {
        var sec = section(title, title.indexOf('well') !== -1 ? 'fa-thumbs-up' : 'fa-lightbulb');
        if (!items || !items.length) {
            sec.appendChild(el('p', 'an-muted', emptyText));
            return sec;
        }
        var ul = el('ul', 'an-comments');
        items.forEach(function (c) { ul.appendChild(el('li', null, c)); });
        sec.appendChild(ul);
        return sec;
    }

    function buildTeacher(t) {
        bodyEl.replaceChildren();

        // Categories
        var catSec = section('Average by category', 'fa-layer-group');
        Object.keys(data.categories).forEach(function (key) {
            var v = t.categories ? t.categories[key] : null;
            catSec.appendChild(barRow(data.categories[key].label, v, pct(v), fmt(v)));
        });
        bodyEl.appendChild(catSec);

        // Per-question
        var qSec = section('Question by question', 'fa-list-check');
        Object.keys(data.categories).forEach(function (catKey) {
            qSec.appendChild(el('div', 'an-q-group', data.categories[catKey].label));
            Object.keys(data.questions).forEach(function (qKey) {
                var q = data.questions[qKey];
                if (q.category !== catKey) return;
                var v = t.questions ? t.questions[qKey] : null;
                var row = el('div', 'an-q-row');
                row.appendChild(el('div', 'an-q-text', q.text));
                var right = el('div', 'an-q-score');
                var track = el('div', 'an-mini-track');
                var fill = el('div', 'an-mini-fill');
                fill.style.width = pct(v) + '%';
                track.appendChild(fill);
                right.appendChild(track);
                right.appendChild(el('strong', null, fmt(v)));
                row.appendChild(right);
                qSec.appendChild(row);
            });
        });
        bodyEl.appendChild(qSec);

        // Distribution
        var dSec = section('How students rated', 'fa-chart-simple');
        var dist = t.distribution || {};
        var total = 0;
        [1, 2, 3, 4, 5].forEach(function (n) { total += Number(dist[n] || 0); });
        [5, 4, 3, 2, 1].forEach(function (n) {
            var c = Number(dist[n] || 0);
            var p = total ? Math.round(c / total * 100) : 0;
            dSec.appendChild(barRow(n + ' \u00b7 ' + (data.scale[n] || ''), c, p, p + '%', 'an-fill-' + n));
        });
        bodyEl.appendChild(dSec);

        // Classes
        var classes = (t.detail && t.detail.classes) || [];
        if (classes.length) {
            var cSec = section('By class', 'fa-book');
            classes.forEach(function (c) {
                var row = el('div', 'an-q-row');
                row.appendChild(el('div', 'an-q-text', c.label));
                row.appendChild(el('div', 'an-q-score', fmt(c.avg) + ' \u00b7 ' + c.responses + (c.responses === 1 ? ' response' : ' responses')));
                cSec.appendChild(row);
            });
            bodyEl.appendChild(cSec);
        }

        // AI summary (per teacher)
        var aiSec = section('AI summary', 'fa-wand-magic-sparkles');
        aiSec.appendChild(el('p', 'an-muted',
            'Generated on request and not saved. Closing this panel discards it.'));
        var out = el('div', 'an-ai-result');
        out.setAttribute('aria-live', 'polite');
        var btn = el('button', 'btn btn-primary');
        btn.type = 'button';
        setButton(btn, 'fa-wand-magic-sparkles', 'Generate summary');
        if (t.responses < data.minResponses) {
            btn.disabled = true;
            aiSec.appendChild(btn);
            aiSec.appendChild(el('p', 'an-hint',
                'Needs at least ' + data.minResponses + ' responses (currently ' + t.responses + ') to protect student anonymity.'));
        } else {
            btn.addEventListener('click', function () { requestSummary(t.teacher_id, btn, out); });
            aiSec.appendChild(btn);
        }
        aiSec.appendChild(out);
        bodyEl.appendChild(aiSec);

        // Comments (already in random order from the server)
        var d = t.detail || {};
        bodyEl.appendChild(commentList('What students say this teacher does well', d.strengths,
            'No written comments for this question.'));
        bodyEl.appendChild(commentList('What students say could improve', d.improvements,
            'No written comments for this question.'));
    }

    function openTeacher(id) {
        var t = teachers[id];
        if (!t) return;
        lastFocus = document.activeElement;

        titleEl.textContent = t.name;
        metaEl.replaceChildren();
        metaEl.appendChild(el('span', 'an-pill ' + t.band.class, t.band.label));
        metaEl.appendChild(el('span', null, fmt(t.overall) + ' / 5'));
        metaEl.appendChild(el('span', null, t.responses + (t.responses === 1 ? ' response' : ' responses')));
        buildTeacher(t);

        overlay.hidden = false;
        drawer.hidden = false;
        document.body.classList.add('an-noscroll');
        drawer.scrollTop = 0;
        bodyEl.scrollTop = 0;
        closeBtn.focus();
    }

    function closeDrawer() {
        if (drawer.hidden) return;
        drawer.hidden = true;
        overlay.hidden = true;
        document.body.classList.remove('an-noscroll');
        bodyEl.replaceChildren(); // drops any AI summary that was on screen
        if (lastFocus && lastFocus.focus) lastFocus.focus();
    }

    document.querySelectorAll('[data-teacher]').forEach(function (btn) {
        btn.addEventListener('click', function () { openTeacher(btn.getAttribute('data-teacher')); });
    });
    if (closeBtn) closeBtn.addEventListener('click', closeDrawer);
    if (overlay) overlay.addEventListener('click', closeDrawer);
    document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape') closeDrawer();
    });
})();
