/**
 * Remember Me configuration.
 * The token is the same 64-character random token already stored in
 * users.current_session_token, so the existing single-device login
 * rule is preserved: a new login invalidates the previous token.
 */
const REMEMBER_COOKIE = 'sua_remember_token';
const REMEMBER_DAYS = 30;

function setRememberCookie($token) {
    $expires = time() + (REMEMBER_DAYS * 24 * 60 * 60);
    $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || ((int)($_SERVER['SERVER_PORT'] ?? 0) === 443);

    setcookie(REMEMBER_COOKIE, $token, [
        'expires' => $expires,
        'path' => '/',
        'secure' => $secure,
        'httponly' => true,
        'samesite' => 'Lax'
    ]);
}

function clearRememberCookie() {
    $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || ((int)($_SERVER['SERVER_PORT'] ?? 0) === 443);

    setcookie(REMEMBER_COOKIE, '', [
        'expires' => time() - 3600,
        'path' => '/',
        'secure' => $secure,
        'httponly' => true,
        'samesite' => 'Lax'
    ]);
}

function redirectByRole($role) {
    if ($role === 'admin') {
        header("Location: " . adminLandingUrl());
    } elseif ($role === 'teacher') {
        header("Location: teacher/dashboard.php");
    } else {
        header("Location: student/dashboard.php");
    }
    exit();
}

/*
 * Restore a remembered login before displaying the login form.
 * This runs only when there is no active PHP session.
 */
if (!isset($_SESSION['user_id']) && !empty($_COOKIE[REMEMBER_COOKIE])) {
    $rememberToken = $_COOKIE[REMEMBER_COOKIE];

    // Tokens generated by random_bytes(32) are exactly 64 hex characters.
    if (preg_match('/^[a-f0-9]{64}$/', $rememberToken)) {
        $rememberStmt = $conn->prepare(
            "SELECT id, username, role, current_session_token FROM users WHERE current_session_token=? AND status='active' LIMIT 1"
        );
        $rememberStmt->bind_param("s", $rememberToken);
        $rememberStmt->execute();
        $rememberResult = $rememberStmt->get_result();

        if ($rememberResult->num_rows === 1) {
            $rememberedUser = $rememberResult->fetch_assoc();

            $_SESSION['user_id'] = $rememberedUser['id'];
            $_SESSION['username'] = $rememberedUser['username'];
            $_SESSION['role'] = $rememberedUser['role'];
            $_SESSION['session_token'] = $rememberedUser['current_session_token'];

            redirectByRole($rememberedUser['role']);
        }
    }

    // Invalid, expired, or superseded token — remove it from the browser.
    clearRememberCookie();
}

if(isset($_POST['login'])){

    $username = trim($_POST['username']);
    $password = trim($_POST['password']);
    $remember = isset($_POST['remember']) && $_POST['remember'] === '1';

    $stmt = $conn->prepare("SELECT * FROM users WHERE username=? AND status='active'");
    $stmt->bind_param("s", $username);
    $stmt->execute();

    $result = $stmt->get_result();

    if($result->num_rows > 0){

        $user = $result->fetch_assoc();

        $passwordMatches = false;

        if(password_get_info($user['password'])['algo'] !== null){
            $passwordMatches = password_verify($password, $user['password']);
        } else {
            if($password === $user['password']){
                $passwordMatches = true;

                $newHash = password_hash($password, PASSWORD_DEFAULT);
                $updateStmt = $conn->prepare("UPDATE users SET password=? WHERE id=?");
                $updateStmt->bind_param("si", $newHash, $user['id']);
                $updateStmt->execute();
            }
        }

        if($passwordMatches){
            $sessionToken = bin2hex(random_bytes(32));

            // Rotate the token on every real login. This keeps the existing
            // single-device rule: any previous session/remember cookie stops working.
            $tokenStmt = $conn->prepare("UPDATE users SET current_session_token=? WHERE id=?");
            $tokenStmt->bind_param("si", $sessionToken, $user['id']);
            $tokenStmt->execute();

            // Prevent session fixation after successful authentication.
            session_regenerate_id(true);

            $_SESSION['user_id'] = $user['id'];
            $_SESSION['username'] = $user['username'];
            $_SESSION['role'] = $user['role'];
            $_SESSION['session_token'] = $sessionToken;

            if ($remember) {
                // Persistent login for 30 days. The cookie is HttpOnly and
                // SameSite=Lax so JavaScript cannot read the bearer token.
                setRememberCookie($sessionToken);

                // Also make the PHP session cookie survive a browser restart
                // while Remember Me is enabled. Closing a tab already keeps
                // a normal session alive; this handles browser restarts too.
                $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || ((int)($_SERVER['SERVER_PORT'] ?? 0) === 443);
                setcookie(session_name(), session_id(), [
                    'expires' => time() + (REMEMBER_DAYS * 24 * 60 * 60),
                    'path' => '/',
                    'secure' => $secure,
                    'httponly' => true,
                    'samesite' => 'Lax'
                ]);
            } else {
                // Do not leave an older persistent Remember Me cookie active
                // when the user explicitly chooses not to be remembered.
                clearRememberCookie();
            }

            redirectByRole($user['role']);

        } else {
            $message = "Invalid Username or Password";
        }

    } else {
        $message = "Invalid Username or Password";
    }
}
